CREATE TABLE radar_campaign_verification_attempts (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    offering_id BIGINT NOT NULL REFERENCES radar_offerings(id),
    campaign_url VARCHAR(2048),
    observed_at TIMESTAMP NOT NULL,
    page_state VARCHAR(40) NOT NULL,
    attempt_key VARCHAR(64) NOT NULL,
    payload_json TEXT NOT NULL,
    CONSTRAINT uq_campaign_verification_attempt UNIQUE (offering_id, attempt_key)
);

CREATE INDEX idx_campaign_verification_history
    ON radar_campaign_verification_attempts (offering_id, observed_at DESC, id DESC);

CREATE INDEX idx_campaign_verified_url_history
    ON radar_campaign_verification_attempts (offering_id, campaign_url, page_state, observed_at DESC, id DESC);
