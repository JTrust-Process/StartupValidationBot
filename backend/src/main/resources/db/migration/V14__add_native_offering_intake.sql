    last_success_at TIMESTAMP,
    last_status VARCHAR(40) NOT NULL,
    directory_fetched BOOLEAN NOT NULL DEFAULT FALSE,
    requests_made INTEGER NOT NULL DEFAULT 0,
    detail_requests INTEGER NOT NULL DEFAULT 0,
    candidates_found INTEGER NOT NULL DEFAULT 0,
    active_candidates INTEGER NOT NULL DEFAULT 0,
    offerings_inserted INTEGER NOT NULL DEFAULT 0,
    companies_matched INTEGER NOT NULL DEFAULT 0,
    candidates_rejected INTEGER NOT NULL DEFAULT 0,
    last_error VARCHAR(2000),
    updated_at TIMESTAMP NOT NULL
);
