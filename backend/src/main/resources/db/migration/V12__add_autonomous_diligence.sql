    updated_at TIMESTAMP NOT NULL
);

CREATE TABLE radar_notification_events (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    event_type VARCHAR(60) NOT NULL,
    entity_type VARCHAR(60) NOT NULL,
    entity_id BIGINT NOT NULL,
    fingerprint VARCHAR(64) NOT NULL,
    recipient VARCHAR(320),
    status VARCHAR(40) NOT NULL,
    subject VARCHAR(500) NOT NULL,
    text_body TEXT NOT NULL,
    html_body TEXT NOT NULL,
    resend_message_id VARCHAR(240),
    attempt_count INTEGER NOT NULL DEFAULT 0,
    last_error VARCHAR(2000),
    created_at TIMESTAMP NOT NULL,
    sent_at TIMESTAMP,
    updated_at TIMESTAMP NOT NULL,
    CONSTRAINT uq_radar_notification_fingerprint UNIQUE (fingerprint)
);

CREATE INDEX idx_radar_notification_pending ON radar_notification_events(status, created_at);
